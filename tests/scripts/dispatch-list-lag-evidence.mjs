function normalizeJobStatus(st) {
  const s = String(st || '').trim();
  if (!s) return 'Pending';
  const lower = s.toLowerCase();
  if (lower === 'queued') return 'Queued';
  if (lower === 'assigned') return 'Assigned';
  if (lower === 'active') return 'Active';
  if (lower === 'pending') return 'Pending';
  if (lower === 'completed') return 'Completed';
  return s;
}

function jobTabForStatus(job) {
  const st = normalizeJobStatus(job.status);
  const drv = String(job.driverId ?? '').trim();
  const hasDriver = drv && drv !== '0' && drv !== '-1' && drv !== '-2';
  if (st === 'Queued' && hasDriver) return 'queue';
  if (['Assigned', 'Picking', 'Arrived'].includes(st)) return 'assign';
  if (['Active', 'OnTrip'].includes(st)) return 'active';
  return 'ua';
}

